import { readFile, writeFile } from 'node:fs/promises';
const header='// GENERATED from assets/data.js and assets/core.js. Do not edit this file directly.\n';
const files=await Promise.all(['data.js','core.js'].map(name=>readFile(new URL('../assets/'+name,import.meta.url),'utf8')));
await writeFile(new URL('../apps-script/Shared.gs',import.meta.url),header+files.join('\n\n'),'utf8');
console.log('Shared.gs synchronized with browser question definitions and analysis.');
